"""Human-readable and JSON reporting for PressAudit findings."""

from __future__ import annotations

import json

SEVERITY_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}


def sort_findings(findings):
    return sorted(findings,
                  key=lambda f: (SEVERITY_ORDER.get(f.severity, 5), f.check_id))


def format_text(target, findings, core_version=None):
    lines = []
    lines.append("PressAudit scan: %s" % target)
    if core_version:
        lines.append("WordPress core: %s" % core_version)
    counts = {}
    for finding in findings:
        counts[finding.severity] = counts.get(finding.severity, 0) + 1
    summary = ", ".join("%s: %d" % (sev, counts[sev])
                        for sev in ("high", "medium", "low", "info")
                        if counts.get(sev))
    lines.append("Findings: %s" % (summary or "none"))
    lines.append("")
    for finding in sort_findings(findings):
        lines.append("[%s] %s (%s)" % (finding.severity.upper(),
                                       finding.title, finding.check_id))
        lines.append("    %s" % finding.detail)
        if finding.evidence:
            lines.append("    Evidence: %s" % finding.evidence)
        if finding.remediation:
            lines.append("    Fix: %s" % finding.remediation)
        if finding.refs:
            lines.append("    Refs: %s" % ", ".join(finding.refs))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def format_json(target, findings, scanner=None):
    return json.dumps({
        "target": target,
        "wordpress": bool(scanner and scanner.is_wordpress),
        "core_version": scanner.core_version if scanner else None,
        "plugins": scanner.plugins if scanner else {},
        "themes": scanner.themes if scanner else {},
        "findings": [f.to_dict() for f in sort_findings(findings)],
    }, indent=2)


def _escape(text):
    return (str(text).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def format_html(target, findings, scanner=None):
    """Standalone HTML report (no external resources)."""
    counts = {}
    for finding in findings:
        counts[finding.severity] = counts.get(finding.severity, 0) + 1
    summary = ", ".join("%s: %d" % (sev, counts[sev])
                        for sev in ("high", "medium", "low", "info")
                        if counts.get(sev)) or "no findings"
    rows = []
    for finding in sort_findings(findings):
        refs = "".join(
            '<a href="%s">%s</a><br>' % (_escape(ref), _escape(ref))
            for ref in finding.refs)
        rows.append(
            '<tr class="sev-%s"><td>%s</td><td>%s</td><td><strong>%s</strong><br>%s'
            '%s%s%s</td></tr>' % (
                _escape(finding.severity),
                _escape(finding.severity.upper()),
                _escape(finding.check_id),
                _escape(finding.title),
                _escape(finding.detail),
                "<br><em>Evidence:</em> " + _escape(finding.evidence)
                if finding.evidence else "",
                "<br><em>Fix:</em> " + _escape(finding.remediation)
                if finding.remediation else "",
                "<br><em>Refs:</em> " + refs if refs else "",
            ))
    core = scanner.core_version if scanner else None
    return """<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>PressAudit report: %s</title>
<style>body{font-family:system-ui,sans-serif;max-width:900px;margin:2em auto;padding:0 1em}
table{border-collapse:collapse;width:100%%}
td,th{border:1px solid #ccc;padding:.5em;text-align:left;vertical-align:top}
.sev-high{background:#fde8e8}.sev-medium{background:#fff3cd}.sev-low{background:#e8f4fd}.sev-info{background:#f2f2f2}
</style></head><body>
<h1>PressAudit report</h1>
<p><strong>Target:</strong> %s</p>
%s
<p><strong>Findings:</strong> %s</p>
<table><tr><th>Severity</th><th>ID</th><th>Finding</th></tr>
%s
</table>
<p><em>Generated by PressAudit. Detection only — no exploitation was performed.</em></p>
</body></html>
""" % (_escape(target), _escape(target),
       "<p><strong>WordPress core:</strong> %s</p>" % _escape(core) if core else "",
       _escape(summary), "\n".join(rows))
